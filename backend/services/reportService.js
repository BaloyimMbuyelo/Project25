// Implements System Design P10: totals are calculated on the server from
// stored transactions (no manual totals), with print and CSV export.

const { db } = require('../config/db');
const settings = require('../config/settings');
const repo = require('../repositories/reportRepository');
const { logAudit } = require('./auditService');
const { badRequest } = require('../utils/errors');
const { toCents, fromCents } = require('../utils/format');

const TITLES = {
    orders: 'Sales / Orders',
    payments: 'Payments by method',
    reservations: 'Reservations',
    stock: 'Stock & low stock'
};

const num = (value) => Number(value || 0);
const pct = (part, whole) => (whole > 0 ? Number(((part / whole) * 100).toFixed(1)) : 0);

// ---------- Pure helpers (unit tested) ----------

function validateRange(from, to, maxDays = settings.REPORT_MAX_DAYS) {
    if (to < from) {
        throw badRequest("'To' cannot be before 'From'.", [{ field: 'to', message: "'To' cannot be before 'From'." }]);
    }
    const days = Math.round((new Date(`${to}T00:00:00`) - new Date(`${from}T00:00:00`)) / 86400000);
    if (days > maxDays) {
        const message = `The date range can be at most ${maxDays} days.`;
        throw badRequest(message, [{ field: 'from', message }]);
    }
    return days + 1;
}

function stockStatus(onHand, reorder) {
    if (toCents(onHand) <= 0) return 'OUT';
    if (toCents(onHand) <= toCents(reorder)) return 'LOW';
    return 'OK';
}

// CSV with UTF-8 BOM so Excel opens it correctly (Table 13). Text cells that
// start with = + - @ are prefixed with ' to block formula injection.
function toCsv({ title, from, to, generatedAt, generatedBy, filters, columns, rows, totals }) {
    const escape = (value) => {
        if (value === null || value === undefined) return '';
        let text = String(value);
        if (typeof value === 'string' && /^[=+\-@\t\r]/.test(text)) text = `'${text}`;
        return /[",\r\n]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
    };
    const line = (cells) => cells.map(escape).join(',');

    const out = [
        line(['Report', title]),
        line(['From', from]),
        line(['To', to]),
        ...Object.entries(filters).filter(([, v]) => v).map(([k, v]) => line([k, v])),
        line(['Generated', generatedAt]),
        line(['Generated by', generatedBy]),
        '',
        line(columns.map((c) => c.label)),
        ...rows.map((row) => line(columns.map((c) => row[c.key]))),
    ];

    if (totals) out.push(line(columns.map((c, i) => (i === 0 ? 'Total' : totals[c.key] ?? ''))));

    return `﻿${out.join('\r\n')}\r\n`;
}

// ---------- Report builders ----------

async function ordersReport({ from, to, order_type: orderType }) {
    const raw = await repo.ordersByDay(db, { from, to, orderType });
    const rows = raw.map((r) => ({
        day: r.day,
        orders: num(r.orders),
        dine_in: num(r.dine_in),
        collection: num(r.collection),
        revenue: num(r.revenue),
        cancelled: num(r.cancelled)
    }));

    const orders = rows.reduce((s, r) => s + r.orders, 0);
    const cancelled = rows.reduce((s, r) => s + r.cancelled, 0);
    const revenueCents = rows.reduce((s, r) => s + toCents(r.revenue), 0);
    const paidOrders = orders - cancelled;

    return {
        columns: [
            { key: 'day', label: 'Date', format: 'date' },
            { key: 'orders', label: 'Orders', format: 'number' },
            { key: 'dine_in', label: 'Dine-in', format: 'number' },
            { key: 'collection', label: 'Collection', format: 'number' },
            { key: 'revenue', label: 'Revenue (R)', format: 'money' },
            { key: 'cancelled', label: 'Cancelled', format: 'number' }
        ],
        rows,
        totals: {
            orders,
            dine_in: rows.reduce((s, r) => s + r.dine_in, 0),
            collection: rows.reduce((s, r) => s + r.collection, 0),
            revenue: fromCents(revenueCents),
            cancelled
        },
        summary: {
            orders,
            revenue: fromCents(revenueCents),
            average_order: paidOrders > 0 ? fromCents(Math.round(revenueCents / paidOrders)) : 0,
            cancelled,
            cancelled_pct: pct(cancelled, orders)
        }
    };
}

async function paymentsReport({ from, to, payment_method_id: methodId }) {
    const raw = await repo.paymentsByDay(db, { from, to, methodId });
    const rows = raw.map((r) => ({
        day: r.day,
        method_name: r.method_name,
        payments: num(r.payments),
        total: num(r.total),
        voided: num(r.voided)
    }));

    const totalCents = rows.reduce((s, r) => s + toCents(r.total), 0);
    const byMethod = {};
    for (const r of rows) {
        byMethod[r.method_name] = byMethod[r.method_name] || { method_name: r.method_name, payments: 0, cents: 0 };
        byMethod[r.method_name].payments += r.payments;
        byMethod[r.method_name].cents += toCents(r.total);
    }

    const payments = rows.reduce((s, r) => s + r.payments, 0);
    const voided = rows.reduce((s, r) => s + r.voided, 0);

    return {
        columns: [
            { key: 'day', label: 'Date', format: 'date' },
            { key: 'method_name', label: 'Method', format: 'text' },
            { key: 'payments', label: 'Payments', format: 'number' },
            { key: 'total', label: 'Total (R)', format: 'money' },
            { key: 'voided', label: 'Voided', format: 'number' }
        ],
        rows,
        totals: { payments, total: fromCents(totalCents), voided },
        summary: {
            payments,
            total: fromCents(totalCents),
            voided,
            by_method: Object.values(byMethod).map(({ cents, ...rest }) => ({ ...rest, total: fromCents(cents) }))
        }
    };
}

async function reservationsReport({ from, to }) {
    const raw = await repo.reservationsByDay(db, { from, to });
    const keys = ['bookings', 'guests', 'pending', 'confirmed', 'seated', 'completed', 'cancelled', 'no_show'];
    const rows = raw.map((r) => ({ day: r.day, ...Object.fromEntries(keys.map((k) => [k, num(r[k])])) }));
    const totals = Object.fromEntries(keys.map((k) => [k, rows.reduce((s, r) => s + r[k], 0)]));

    // No-show rate over bookings that were not cancelled in advance
    const attended = totals.completed + totals.seated + totals.no_show;

    return {
        columns: [
            { key: 'day', label: 'Date', format: 'date' },
            { key: 'bookings', label: 'Bookings', format: 'number' },
            { key: 'guests', label: 'Guests', format: 'number' },
            { key: 'confirmed', label: 'Confirmed', format: 'number' },
            { key: 'seated', label: 'Seated', format: 'number' },
            { key: 'completed', label: 'Completed', format: 'number' },
            { key: 'cancelled', label: 'Cancelled', format: 'number' },
            { key: 'no_show', label: 'No-show', format: 'number' }
        ],
        rows,
        totals,
        summary: {
            bookings: totals.bookings,
            guests: totals.guests,
            cancelled: totals.cancelled,
            no_show: totals.no_show,
            no_show_rate: pct(totals.no_show, attended)
        }
    };
}

async function stockReport({ from, to }) {
    const raw = await repo.stockSummary(db, { from, to });
    const rows = raw.map((r) => ({
        item_name: r.item_name,
        category: r.category,
        unit: r.unit,
        on_hand: num(r.on_hand),
        reorder_level: num(r.reorder_level),
        status: stockStatus(r.on_hand, r.reorder_level),
        received: num(r.received),
        used: num(r.used),
        wasted: num(r.wasted),
        adjusted_out: num(r.adjusted_out),
        movements: num(r.movements)
    }));

    return {
        columns: [
            { key: 'item_name', label: 'Item', format: 'text' },
            { key: 'unit', label: 'Unit', format: 'text' },
            { key: 'on_hand', label: 'On hand', format: 'quantity' },
            { key: 'reorder_level', label: 'Reorder level', format: 'quantity' },
            { key: 'status', label: 'Status', format: 'text' },
            { key: 'received', label: 'Received', format: 'quantity' },
            { key: 'used', label: 'Used', format: 'quantity' },
            { key: 'wasted', label: 'Wasted', format: 'quantity' },
            { key: 'movements', label: 'Movements', format: 'number' }
        ],
        rows,
        totals: null, // units differ between items, so quantities are not summed
        summary: {
            items: rows.length,
            low: rows.filter((r) => r.status === 'LOW').length,
            out: rows.filter((r) => r.status === 'OUT').length,
            items_with_wastage: rows.filter((r) => r.wasted > 0).length,
            movements: rows.reduce((s, r) => s + r.movements, 0)
        }
    };
}

const BUILDERS = {
    orders: ordersReport,
    payments: paymentsReport,
    reservations: reservationsReport,
    stock: stockReport
};

// P10 - GenerateReport(user, type, from, to, filters)
async function generateReport(user, type, query, ip, now = new Date()) {
    const { from, to, format = 'json', ...filters } = query;
    validateRange(from, to);

    const report = await BUILDERS[type]({ from, to, ...filters });

    await logAudit(db, {
        userId: user.user_id,
        action: 'REPORT_RUN',
        entity: 'reports',
        ip,
        details: { type, from, to, format, filters }
    });

    const result = {
        type,
        title: TITLES[type],
        from,
        to,
        filters,
        generated_at: now.toISOString(),
        generated_by: user.full_name,
        ...report
    };

    if (format === 'csv') {
        return {
            csv: toCsv({
                title: result.title,
                from,
                to,
                generatedAt: now.toLocaleString('en-ZA'),
                generatedBy: user.full_name,
                filters,
                columns: report.columns,
                rows: report.rows,
                totals: report.totals
            }),
            filename: `ubms-${type}-${from}-to-${to}.csv`
        };
    }

    return result;
}

module.exports = { TITLES, validateRange, toCsv, generateReport };
